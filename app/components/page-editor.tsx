let grapejsModule: typeof import("grapesjs") | null = null;
let blocksModule: typeof import("grapesjs-blocks-basic") | null = null;

async function loadGrapes() {
  if (grapejsModule) return { grapesjs: grapejsModule, blocks: blocksModule! };
  const [gjs, blocks] = await Promise.all([
    import("grapesjs"),
    import("grapesjs-blocks-basic"),
  ]);
  await import("grapesjs/dist/css/grapes.min.css");
  grapejsModule = gjs;
  blocksModule = blocks;
  return { grapesjs: gjs, blocks };
}

function updateTailwindFontConfig(
  editor: import("grapesjs").Editor,
  loadedFontUrls: string[]
) {
  const frame = editor.Canvas.getFrameEl();
  if (!frame?.contentWindow) return;
  const win = frame.contentWindow as Window & { tailwind?: { config?: Record<string, unknown> } };

  // Extract font family names from Google Font URLs
  const fontFamilies: Record<string, string[]> = {};
  for (const url of loadedFontUrls) {
    const match = url.match(/family=([^&:]+)/);
    if (match) {
      const family = match[1].replace(/\+/g, " ");
      const key = family.toLowerCase().replace(/\s+/g, "-");
      fontFamilies[key] = [`'${family}'`, "sans-serif"];
    }
  }

  if (win.tailwind) {
    win.tailwind.config = {
      theme: {
        extend: {
          fontFamily: fontFamilies,
        },
      },
    };
  }
}

function extractCompiledTailwindCss(
  editor: import("grapesjs").Editor
): string {
  const frame = editor.Canvas.getFrameEl();
  if (!frame?.contentDocument) return "";
  const doc = frame.contentDocument;

  // Tailwind CDN generates styles in a <style> element
  // Look for the one generated by Tailwind (usually has a lot of content)
  let tailwindCss = "";
  for (const style of Array.from(doc.querySelectorAll("style"))) {
    const text = style.textContent ?? "";
    // Tailwind CDN generates styles with utility classes - detect by common patterns
    if (text.includes("--tw-") || text.includes("tailwindcss") || text.length > 5000) {
      tailwindCss = text;
      break;
    }
  }
  return tailwindCss;
}

function injectResources(
  editor: import("grapesjs").Editor,
  styles: string[],
  scripts: string[]
) {
  const frame = editor.Canvas.getFrameEl();
  if (!frame?.contentDocument) return;
  const doc = frame.contentDocument;

  for (const url of styles) {
    if (doc.querySelector(`link[href="${url}"]`)) continue;
    const link = doc.createElement("link");
    link.rel = "stylesheet";
    link.href = url;
    doc.head.appendChild(link);
  }

  for (const url of scripts) {
    if (doc.querySelector(`script[src="${url}"]`)) continue;
    const script = doc.createElement("script");
    script.src = url;
    doc.head.appendChild(script);
  }
}

