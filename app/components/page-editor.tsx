function isGradientClass(c: string): boolean {
  return (
    c.startsWith("bg-gradient-") ||
    c.startsWith("from-") ||
    c.startsWith("via-") ||
    c.startsWith("to-") ||
    c === "bg-clip-text" ||
    c === "text-transparent"
  );
}

