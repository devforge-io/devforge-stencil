    // Compiled Tailwind utilities (self-contained, no CDN needed at runtime)
    if (tailwindCss) {
      parts.push("/* Compiled Tailwind CSS */");
      parts.push(tailwindCss);
    }

    // GrapesJS component styles
    if (css.trim()) {
      parts.push("/* Component styles */");
      parts.push(css);
    }

    const compiledCss = parts.join("\n");

    onSave(projectJson, html, compiledCss);
